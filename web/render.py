"""Deterministic Markdown -> HTML for generated and manual docs.

Supports headings (including the generated ``<a id="...">`` anchors),
paragraphs, **bold**, *italic*, `code`, [links](url), images,
fenced code blocks (wrapped in closed-by-default ``<details>`` zones,
with a following "Call graph" list in its own zone), bullet and ordered
lists (nested to any depth), blockquotes, tables (with ``\\|`` escaped
pipes) and ``---`` rules.

Safety: only the anchor/span tags kodama-docs itself emits pass through;
all other HTML is escaped, and script/data URLs are rejected. Output is a
pure function of the input text; no third-party dependencies (syntax
highlighting is client-side highlight.js, loaded by the page).
"""
import html
import re

_TAG_RE = re.compile(r'<[^<>\n]+>')
# Only the tags kodama-docs itself emits may pass through. Anything else is
# escaped as text: LLM prose and manual pages must not inject markup.
_SAFE_TAG_RE = re.compile(
    r'^</?(?:'
    r'a(?:\s+id="[^"]*")?'
    r'|span(?:\s+style="color:#[0-9A-Fa-f]{6}")?'
    r')>$')
_CODE_RE = re.compile(r'`([^`\n]+)`')
_BOLD_RE = re.compile(r'\*\*(.+?)\*\*')
_STAR_RE = re.compile(r'\*([^*\n]+)\*')
_UNDER_RE = re.compile(r'(?<!\w)_([^_\n]+)_(?!\w)')
_INTRA_U_RE = re.compile(r'(?<=\w)_(?=\w)')
_LINK_RE = re.compile(r'\[([^\]]+)\]\(([^)\s]+)\)')
_IMG_RE = re.compile(r'!\[([^\]]*)\]\(([^)\s]+)\)')
_STASH_RE = re.compile(r'\x00(\d+)\x00')
_HEAD_RE = re.compile(r'^(#{1,6})\s+(.*)$')
_HR_RE = re.compile(r'^-{3,}\s*$')
_OL_RE = re.compile(r'^\d+\.\s+')


def _safe_url(url: str) -> str:
    """Allow only ordinary relative/absolute links, never script URLs."""
    u = str(url or '').strip()
    low = u.lower()
    if low.startswith(('javascript:', 'vbscript:', 'data:')):
        return '#'
    # has an explicit scheme? permit the harmless ones
    m = re.match(r'^([A-Za-z][A-Za-z0-9+.-]*):', u)
    if m and m.group(1).lower() not in ('http', 'https', 'mailto'):
        return '#'
    return u


def render_inline(text: str) -> str:
    """Inline markdown -> HTML.

    Only the few tags generated by kodama-docs (anchors and the unresolved
    span) pass through; every other tag is escaped. Inline code stays
    literal, links get safe hrefs, and markdown images are supported."""
    stash = []

    def keep_raw(value):
        stash.append(value)
        return f'\x00{len(stash) - 1}\x00'

    def keep_tag(m):
        tag = m.group(0)
        if _SAFE_TAG_RE.match(tag):
            return keep_raw(tag)
        return tag  # html.escape() below escapes it

    text = _TAG_RE.sub(keep_tag, text)   # raw anchors like <a id="fn-x-3">
    text = _CODE_RE.sub(lambda m: keep_raw(m.group(0)), text)  # literal code

    def keep_img(m):
        alt = html.escape(m.group(1), quote=True)
        src = html.escape(_safe_url(m.group(2)), quote=True)
        return keep_raw(f'<img src="{src}" alt="{alt}">')

    text = _IMG_RE.sub(keep_img, text)

    # Links are stashed as complete anchors, protecting both the label and
    # the target from the underscore pass (so __init__.py links survive).
    def keep_link(m):
        label = render_inline(m.group(1))
        href = html.escape(_safe_url(m.group(2)), quote=True)
        return keep_raw(f'<a href="{href}">{label}</a>')

    text = _LINK_RE.sub(keep_link, text)
    text = html.escape(text)
    text = _BOLD_RE.sub(r'<strong>\1</strong>', text)
    text = _STAR_RE.sub(r'<em>\1</em>', text)
    # protect intraword underscores (e.g. kodama_docs) from the italic pass,
    # like GFM's intraword rule
    u_stash = []

    def keep_u(m):
        u_stash.append('_')
        return f'\x01{len(u_stash) - 1}\x01'

    text = _INTRA_U_RE.sub(keep_u, text)
    text = _UNDER_RE.sub(r'<em>\1</em>', text)
    text = re.sub(r'\x01(\d+)\x01', lambda m: '_', text)

    def restore(m):
        item = stash[int(m.group(1))]
        if item.startswith('<'):
            return item
        return '<code>' + html.escape(item[1:-1]) + '</code>'

    return _STASH_RE.sub(restore, text)


def _table_cells(row: str) -> list:
    r = row.strip()
    if r.startswith('|'):
        r = r[1:]
    if r.endswith('|'):
        r = r[:-1]
    return [part.replace('\\|', '|').strip()
            for part in re.split(r'(?<!\\)\|', r)]


def render_table(rows) -> str:
    header = _table_cells(rows[0])
    body = [_table_cells(r) for r in rows[2:]] if len(rows) >= 3 else []
    h = ['<table>', '<thead><tr>']
    h += [f'<th>{render_inline(c)}</th>' for c in header]
    h += ['</tr></thead>', '<tbody>']
    for row in body:
        h.append('<tr>' + ''.join(f'<td>{render_inline(c)}</td>' for c in row)
                 + '</tr>')
    h += ['</tbody>', '</table>']
    return '\n'.join(h)


def render_list(items, ordered: bool = False) -> str:
    """items: (indent, text) pairs; each item indented deeper than the
    one before it nests under the most recent shallower item (arbitrary
    depth). ``ordered`` renders the whole list as <ol> (nested branches
    stay unordered, matching the generated documentation's needs)."""
    tree = []
    stack = []  # (indent, node) — the current branch, shallowest first
    for indent, text in items:
        node = {'text': text, 'children': []}
        while stack and stack[-1][0] >= indent:
            stack.pop()
        (stack[-1][1]['children'] if stack else tree).append(node)
        stack.append((indent, node))
    tag = 'ol' if ordered else 'ul'
    h = [f'<{tag}>']

    def emit(nodes):
        for n in nodes:
            h.append(f'<li>{render_inline(n["text"])}')
            if n['children']:
                h.append('<ul>')
                emit(n['children'])
                h.append('</ul>')
            h.append('</li>')

    emit(tree)
    h.append(f'</{tag}>')
    return '\n'.join(h)


def render_md(md: str) -> str:
    """Markdown text (kodama-docs's generated subset) -> HTML body."""
    lines = md.replace('\r\n', '\n').split('\n')
    out = []
    i, n = 0, len(lines)
    while i < n:
        stripped = lines[i].strip()
        if not stripped:
            i += 1
            continue
        if stripped.startswith('```'):
            lang = stripped[3:].strip()
            i += 1
            buf = []
            while i < n and not lines[i].strip().startswith('```'):
                buf.append(lines[i])
                i += 1
            i += 1  # skip closing fence
            cls = f' class="lang-{lang}"' if lang else ''
            pre = (f'<pre><code{cls}>'
                   f'{html.escape(chr(10).join(buf))}</code></pre>')
            # Two separate collapsible zones, both closed by default:
            # the source, and (when present) its "Call graph" list.
            j = i
            while j < n and not lines[j].strip():
                j += 1
            if j < n and lines[j].strip() == '**Call graph**':
                j += 1
                while j < n and not lines[j].strip():
                    j += 1
                items = []
                while j < n and lines[j].strip().startswith('- '):
                    raw = lines[j]
                    items.append((len(raw) - len(raw.lstrip()),
                                 raw.strip()[2:]))
                    j += 1
                if items:
                    out.append('<details class="src">'
                               '<summary>Source</summary>\n'
                               + pre + '\n</details>')
                    out.append('<details class="cg">'
                               '<summary>Call graph</summary>\n'
                               + render_list(items) + '\n</details>')
                    i = j
                    continue
            out.append('<details class="src"><summary>Source</summary>\n'
                       + pre + '\n</details>')
            continue
        m = _HEAD_RE.match(lines[i])
        if m:
            lvl = len(m.group(1))
            out.append(f'<h{lvl}>{render_inline(m.group(2))}</h{lvl}>')
            i += 1
            continue
        if _HR_RE.match(stripped):
            out.append('<hr>')
            i += 1
            continue
        if stripped.startswith('|'):
            rows = []
            while i < n and lines[i].strip().startswith('|'):
                rows.append(lines[i])
                i += 1
            out.append(render_table(rows))
            continue
        if stripped.startswith('- '):
            items = []
            while i < n and lines[i].strip().startswith('- '):
                raw = lines[i]
                indent = len(raw) - len(raw.lstrip())
                items.append((indent, raw.strip()[2:]))
                i += 1
            out.append(render_list(items))
            continue
        if _OL_RE.match(stripped):
            items = []
            while i < n and _OL_RE.match(lines[i].strip()):
                raw = lines[i]
                indent = len(raw) - len(raw.lstrip())
                text = _OL_RE.sub('', raw.strip(), count=1)
                items.append((indent, text))
                i += 1
            out.append(render_list(items, ordered=True))
            continue
        if stripped.startswith('>'):
            buf = []
            while i < n and lines[i].strip().startswith('>'):
                buf.append(re.sub(r'^\s*>\s?', '', lines[i]))
                i += 1
            out.append('<blockquote>'
                       + render_md('\n'.join(buf))
                       + '</blockquote>')
            continue
        # paragraph: until a blank line or another block start
        buf = [lines[i].strip()]
        i += 1
        while (i < n and lines[i].strip()
               and not lines[i].lstrip().startswith(('#', '```', '|', '- '))
               and not _OL_RE.match(lines[i].strip())
               and not lines[i].strip().startswith('>')
               and not _HR_RE.match(lines[i].strip())):
            buf.append(lines[i].strip())
            i += 1
        out.append('<p>' + render_inline(' '.join(buf)) + '</p>')
    return '\n'.join(out)
